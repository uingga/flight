const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const mod = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/te31-posts.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { module: mod, exports: mod.exports });
const { TE31_POSTS, matchTe31Campaign, unmatchedTe31Campaigns } = mod.exports;
assert.equal(TE31_POSTS.length, 6);
assert.equal(new Set(TE31_POSTS.map(p => p.id)).size, 6);
const campaign = TE31_POSTS[0].campaign;
const correct = { name: campaign, source: 'te31', users: 3, detailOpenUsers: null, bookingClickUsers: 0 };
assert.equal(matchTe31Campaign(campaign, [{ ...correct, source: 'threads' }, correct]), correct);
assert.equal(matchTe31Campaign(campaign, [{ ...correct, name: 'tikitikit_te31' }]), null);
assert.equal(matchTe31Campaign(campaign, null), null);
assert.equal(matchTe31Campaign(null, [correct]), null);
assert.equal(matchTe31Campaign(campaign, []), null);
assert.equal(matchTe31Campaign(campaign, [correct]).detailOpenUsers, null);
assert.equal(matchTe31Campaign(campaign, [correct]).bookingClickUsers, 0);
assert.equal(unmatchedTe31Campaigns([correct, { ...correct, name: 'tikitikit_te31' }, { ...correct, source: 'threads' }]).length, 1);
assert.equal(TE31_POSTS.filter(p => !p.campaign).length, 3);
assert.equal(TE31_POSTS.find(p => p.id === 5196).recommendations, null);
assert.equal(TE31_POSTS[0].id, 5235);
assert.equal(TE31_POSTS[0].campaign, 'tikitikit_te31_icn-260909');
assert.equal(TE31_POSTS[0].link, '/c/te31-icn-260909');
assert.equal(TE31_POSTS[0].views, 114);
assert.equal(TE31_POSTS.find(p => p.id === 5232).views, 133);
assert.equal(TE31_POSTS.find(p => p.id === 5211).views, 179);
assert.equal(TE31_POSTS.find(p => p.id === 5196).observedAt, '2026-09-08T19:40:00+09:00');
assert.notEqual(TE31_POSTS[0].observedAt, TE31_POSTS[0].recommendationsObservedAt);
assert.ok(TE31_POSTS[0].commentNote.includes('작성자'));
assert.equal(unmatchedTe31Campaigns([{ ...correct, name: 'tikitikit_te31_icn-260909' }]).length, 0);
console.log('TE31 campaign matching: all assertions passed');
